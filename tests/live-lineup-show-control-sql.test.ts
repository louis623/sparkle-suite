import { runInNewContext } from 'node:vm'
import { randomUUID } from 'node:crypto'
import { claimSource, configureSourceParties, receiveSource } from '@/lib/live-lineup/service'
import { lineupSqlAdapter } from './fixtures/live-lineup-sql-adapter'
import { readFile } from 'node:fs/promises'
import { PGlite } from '@electric-sql/pglite'
import { expect, it } from 'vitest'

const rep = '11111111-1111-4111-8111-111111111111'
const other = '22222222-2222-4222-8222-222222222222'
const start = '33333333-3333-4333-8333-333333333333'
const stop = '44444444-4444-4444-8444-444444444444'
const sqlFiles = [
  '20260910000100_live_lineup_v2.sql', '20260926000100_live_lineup_atomic_observations.sql',
  '20261113180000_live_lineup_invalid_heartbeat.sql', '20261121190000_live_lineup_show_control.sql',
]

it('serializes authenticated controls, remembers receipts, fences a late first order and persists expiry', async () => {
  const sql = new PGlite()
  try {
    await sql.exec('create role anon; create role authenticated; create role service_role bypassrls; create table reps(id uuid primary key)')
    await sql.query('insert into reps values ($1),($2)',[rep,other])
    for (const file of sqlFiles) await sql.exec(await readFile('supabase/migrations/'+file,'utf8'))
    for (const role of ['anon','authenticated']) {
      await sql.exec('set role '+role)
      await expect(sql.query('select * from live_lineup_show_controls')).rejects.toMatchObject({code:'42501'})
      await expect(sql.query('select live_lineup_control_expire(1)')).rejects.toMatchObject({code:'42501'})
      await sql.exec('reset role')
    }
    await sql.exec('set role service_role')
    const mutate = async (type:string, id:string, revision:number, tenant = rep) => {
      const result = await sql.query("select live_lineup_control_command($1,$2,$3,$4,'workspace') as command",
        [tenant,type,id,revision])
      return result.rows[0].command as {receipt:{run_id:string}}
    }
    await sql.query("select live_lineup_control_checkin($1,'2.0.13','2.0.13','loading',true,true,null)",[rep])
    const first = await mutate('show-start',start,0)
    expect(first).toMatchObject({status:'applied',control:{revision:1,mode:'started',auto_check_new_parties:true}})
    expect(await mutate('show-stop',stop,0)).toMatchObject({status:'conflict',control:{revision:1}})
    const stopped = await mutate('show-stop',stop,1)
    expect(stopped).toMatchObject({control:{mode:'stopped',stop_reason:'manual',stopped_party_ids:[]}})
    expect(await mutate('show-start',start,0)).toMatchObject({receipt:{resulting_revision:1,run_id:first.receipt.run_id},control:{revision:2}})
    await expect(mutate('show-start',stop,2)).rejects.toMatchObject({code:'22023'})
    await sql.query("select live_lineup_control_capture($1,null,$2::jsonb,'configure','{}',clock_timestamp())",[rep,
      JSON.stringify({show:{partyIds:['synthetic-one'],excludedPartyIds:[]}})])
    const stoppedAfterDiscovery = await sql.query('select mode, selection_epoch from live_lineup_show_controls where rep_id=$1',[rep])
    expect(stoppedAfterDiscovery.rows[0]).toMatchObject({mode:'stopped',selection_epoch:0})
    const independent = await mutate('show-start',start,0,other)
    expect(independent).toMatchObject({control:{revision:1,auto_check_new_parties:false}})
    await sql.exec('reset role')
    await sql.query("update live_lineup_show_controls set started_at=clock_timestamp()-interval '121 minutes', idle_deadline_at=clock_timestamp()-interval '1 minute' where rep_id=$1",[other])
    await sql.exec('set role service_role')
    expect((await sql.query('select live_lineup_control_expire(64) as expired')).rows[0]).toEqual({expired:1})
    expect((await sql.query('select mode, stop_reason from live_lineup_show_controls where rep_id=$1',[other])).rows[0])
      .toEqual({mode:'stopped',stop_reason:'idle'})
  } finally {
    await sql.close()
  }
}, 20_000)

const archivedClients = process.env.LIVE_LINEUP_ARCHIVED_CLIENTS

it.runIf(Boolean(archivedClients))('accepts claims and scoped snapshots generated by the three archived publisher clients',async()=>{
  const sql=new PGlite()
  try {
    await sql.exec('create role anon; create role authenticated; create role service_role bypassrls; create table reps(id uuid primary key); create table live_lineup_connection_codes(rep_id uuid,sync_code text,created_at timestamptz default now()); grant select on live_lineup_connection_codes to service_role')
    for (const file of sqlFiles) await sql.exec(await readFile('supabase/migrations/'+file,'utf8'))
    for (const [index,version] of ['2.0.6','2.0.11','2.0.12'].entries()) {
      const tenant=randomUUID(),token='TST-000'+(index+1),documentId=randomUUID()
      await sql.query('insert into reps values($1)',[tenant])
      await sql.query('insert into live_lineup_connection_codes(rep_id,sync_code) values ($1,$2)',[tenant,token])
      await sql.exec('set role service_role')
      const db=lineupSqlAdapter(sql)
      const raw: {SparklePublisherClient?:{createPublisherClient:(options:unknown)=>{sync:(snapshot:unknown,version:string,options:unknown)=>Promise<{status:string}>}}}={}
      runInNewContext(await readFile(archivedClients+'/client-'+version+'.js','utf8'),raw)
      let now=Date.now()-3500,serial=0
      let state:Record<string,unknown>={token,enabled:true,generation:0,configVersion:randomUUID(),needsClaim:true,nextSequence:0}
      const post=async (credential:string,body:Record<string,unknown>)=>{
        now += 600
        if (body.action==='claim') return claimSource(db,credential,body.claimId,now,body.generation,body.capabilities,body.diagnostics)
        if (body.action==='snapshot') return receiveSource(db,credential,body.packet,now)
        throw Error('Unexpected archived action')
      }
      const client=raw.SparklePublisherClient!.createPublisherClient({
        now:()=>now,randomId:randomUUID,post,
        store:{load:async()=>state,update:async(_version:string,patch:Record<string,unknown>)=>{state={...state,...patch};return true}},
      })
      const snapshot=()=>({
        parserState:'ready',reason:null,entries:[{id:'fixture:1',name:'Sample',orderedAt:now-1000}],
        revealedIds:[],revealedEntries:[],readerVersion:version,
        observation:{documentId,serial:++serial,settled:true,serverTime:new Date(now).toISOString()},
      })
      expect(await client.sync(snapshot(),version,{readyHint:true}),version).toMatchObject({status:'confirmed'})
      now+=1000
      const configured=await configureSourceParties(db,token,0,['fixture'],[],now,{
        claimId:state.claimId,epoch:state.epoch,publisherId:state.publisherId,capabilities:'lineup-2.0.5',
      })
      expect(configured).toMatchObject({protocol:2,orderScope:'selected-parties',generation:1})
      state={...state,generation:1,claimId:null,publisherId:null,epoch:null,needsClaim:true,nextSequence:0,nextAttemptAt:0}
      expect(await client.sync(snapshot(),version,{readyHint:true}),version).toMatchObject({status:'confirmed'})
      const row=await sql.query('select mode,run_ready_since from live_lineup_show_controls where rep_id=$1',[tenant])
      expect(row.rows[0]).toMatchObject({mode:'auto',run_ready_since:expect.any(Date)})
      await sql.exec('reset role')
    }
  } finally { await sql.close() }
},20000)
